function request(path, options = []) {
  const target = deployment.includes('.vercel.app') ? [path, '--deployment', deployment] : [deployment + path];
  const result = spawnSync(process.execPath, [cli, 'curl', ...target, '--scope', 'team_GElsejSOv3JCiuXlZNgvnGT5', '--', '--silent', '--show-error', '--write-out', '\n%{http_code}', ...options], { encoding: 'utf8', timeout: 120000 });
  if (result.status !== 0) throw new Error(`Deployment request failed: ${path}`);
  const body = result.stdout.trim();
  const split = body.lastIndexOf('\n');
  return { status: Number(body.slice(split + 1)), body: body.slice(0, split) };
}
